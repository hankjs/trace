def _assert_value(actual, expected, path):
    if isinstance(expected, dict):  # DataFrame 捕获
        assert isinstance(actual, pd.DataFrame), path
        assert list(actual.columns) == expected["columns"], path
        actual_rows = actual.to_numpy().tolist()
        assert len(actual_rows) == len(expected["data"]), path
        for i, (a_row, e_row) in enumerate(zip(actual_rows, expected["data"])):
            for j, (a, e) in enumerate(zip(a_row, e_row)):
                _assert_scalar(a, e, f"{path}[{i}][{j}]")
        return
    if isinstance(expected, list):
        assert isinstance(actual, pd.Series), path
        actual_list = actual.to_numpy().tolist()
        assert len(actual_list) == len(expected), path
        for i, (a, e) in enumerate(zip(actual_list, expected)):
            _assert_scalar(a, e, f"{path}[{i}]")
        return
    _assert_scalar(actual, expected, path)


def _assert_scalar(actual, expected, path):
    if expected is None:
        assert actual is None or (isinstance(actual, float) and math.isnan(actual)) or (
            not isinstance(actual, (bool, np.bool_)) and pd.isna(actual)
        ), path
        return
    if isinstance(expected, bool):
        assert bool(actual) == expected, path
        return
    assert actual == pytest.approx(expected, rel=1e-8, abs=1e-10), path


