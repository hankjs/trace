def _fields():
    rng = np.random.RandomState(42)
    n = 120
    close = 10 * np.exp(np.cumsum(rng.normal(0.001, 0.02, n)))
    open_ = close * (1 + rng.normal(0, 0.005, n))
    high = np.maximum(open_, close) * (1 + np.abs(rng.normal(0, 0.004, n)))
    low = np.minimum(open_, close) * (1 - np.abs(rng.normal(0, 0.004, n)))
    volume = rng.uniform(5e5, 5e6, n).round(0)
    amount = volume * close
    return {
        "open": pd.Series(open_),
        "high": pd.Series(high),
        "low": pd.Series(low),
        "close": pd.Series(close),
        "raw_close": pd.Series(close),
        "volume": pd.Series(volume),
        "amount": pd.Series(amount),
        "is_st": pd.Series(np.zeros(n, dtype=bool)),
    }


def _portfolio_fields(fields):
    dates = pd.date_range("2025-01-06", periods=120, freq="B")
